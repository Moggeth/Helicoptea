import assert from 'node:assert/strict';
import { Gamepads } from '../src/input/gamepad.js';
const p = Object.create(Gamepads.prototype), calls = []; let resets = 0;
const act = { playEffect: (kind, effect) => { calls.push(effect); return Promise.resolve('complete'); }, reset: () => { resets++; } };
p.settings = { rumble: true }; p.active = () => ({ vibrationActuator: act });
p.rumble(0.1, 0.2, 60); p.rumble(1, 0.8, 450, 3); p.rumble(0.9, 1, 320, 2); p.rumble(0.1, 0.3, 60);
assert.equal(calls.length, 2); assert.equal(calls[1].duration, 450);
console.log('PASS  crash pulses override small impacts and survive later contact events');
p.stopRumble(); assert.equal(resets, 1); assert.equal(p.rumbleEffect, null);
p.rumbleEffect = null; p.rumble(0.2, 0.2, 60); p.rumble(0.2, 0.2, 60);
assert.equal(calls.length, 3);
p.rumbleEffect.until = 0; p.rumble(0.2, 0.2, 60); assert.equal(calls.length, 4);
console.log('PASS  repeated contact does not restart a pulse until it expires');
p.stopRumble(); p.settings.rumble = false; p.rumble(1, 1, 90); assert.equal(calls.length, 4);
p.settings.rumble = true; p.rumble(NaN, 1, 90); assert.equal(calls.length, 4);
act.playEffect = () => { throw new Error('disconnected'); };
p.rumble(1, 1, 90); assert.equal(p.rumbleEffect, null);
act.playEffect = () => Promise.reject(new Error('unsupported'));
p.rumble(1, 1, 90); await new Promise(setImmediate); assert.equal(p.rumbleEffect, null);
console.log('PASS  disabled, invalid and unsupported rumble never breaks input handling');
